"""Generate the reproducible model.py exported with each CAD result (SPEC 6.4 outputs).

The file contains the template's own build source plus the exact resolved params and mate clearance,
so running it reproduces the same solid. It imports the shipped template, which keeps the exported
source small and always in step with the library.
"""

from __future__ import annotations

import inspect
import json

from screwit.cad.templates import get_template


def render_model_source(template_name: str, params: dict[str, float],
                        mate_radial_clearance_mm: float | None,
                        placement=None) -> str:
    template = get_template(template_name)
    build_src = inspect.getsource(type(template).build)
    params_json = json.dumps(params, indent=4)
    clr = "None" if mate_radial_clearance_mm is None else repr(mate_radial_clearance_mm)
    cls = type(template).__name__
    if placement is not None:
        place_comment = (
            f"# Scan-frame placement applied to the solid before export (viewer overlays it directly):\n"
            f"#   translate_mm = {list(placement.translate_mm)}\n"
            f"#   rotation_quat (x,y,z,w) = {list(placement.rotation_quat)}"
        )
    else:
        place_comment = "# No scan-frame placement (non-mating part)."
    return f'''"""Reproducible CAD source for template {template_name!r} (Screw It, SPEC 6.4).

Generated by screwit.cad; run this file to rebuild the exact solid in template-local millimetres.
The CAD service additionally places the solid in the scan frame before export; that transform is
recorded below and reported in CadResult.placement.
"""

import cadquery as cq
from cadquery import exporters

from screwit.cad.templates.parts import {cls}

# Resolved parameters (already range-checked):
PARAMS = {params_json}

# Radial clearance copied from the printer profile for the chosen fit (None if the part does not mate):
MATE_RADIAL_CLEARANCE_MM = {clr}

{place_comment}


def build():
    template = {cls}()
    result = template.build(dict(PARAMS), mate_radial_clearance_mm=MATE_RADIAL_CLEARANCE_MM)
    return result.solid


# The template's own build method, for reference (do not edit here; edit the library):
# ----------------------------------------------------------------------------------
{_comment_block(build_src)}

if __name__ == "__main__":
    solid = build()
    exporters.export(solid, "model.stl")
    exporters.export(solid, "model.step")
    print("wrote model.stl and model.step")
'''


def _comment_block(src: str) -> str:
    return "\n".join("# " + line if line else "#" for line in src.rstrip().splitlines())
