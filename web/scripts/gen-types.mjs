// Generate web/lib/contracts.gen.ts from ../fixtures/schema/*.json.
//
// Each JSON Schema is compiled independently, so different schemas emit their
// own copies of shared helper names (CadResult, Check, BomLine, ...). To keep
// one valid TS module we wrap every schema's output in its own `namespace`
// (named after the schema's title) and then re-export the title type at the top
// level under that same name. App code imports the top-level names (Scan, Part,
// CadResult, ...). Deterministic: schemas are processed in sorted order and the
// banner carries no timestamp, so a rerun on unchanged schemas is byte-identical.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "..", "..", "fixtures", "schema");
const outFile = resolve(here, "..", "lib", "contracts.gen.ts");

const COMPILE_OPTS = {
  bannerComment: "",
  additionalProperties: false,
  declareExternallyReferenced: true,
  enableConstEnums: false,
  style: { singleQuote: false, semi: true },
};

// Indent every non-empty line so the block nests cleanly inside a namespace.
function indent(src) {
  return src
    .split("\n")
    .map((line) => (line.length ? "  " + line : line))
    .join("\n");
}

async function main() {
  const files = (await readdir(schemaDir))
    .filter((f) => f.endsWith(".json"))
    .sort();

  const blocks = [];
  const aliases = [];
  for (const file of files) {
    const raw = await readFile(join(schemaDir, file), "utf8");
    const schema = JSON.parse(raw);
    const name = schema.title || file.replace(/\.json$/, "");
    const ns = `${name}NS`;
    const ts = (await compile(schema, name, COMPILE_OPTS)).trim();
    blocks.push(`export namespace ${ns} {\n${indent(ts)}\n}`);
    // The title type is the schema root; surface it at module scope.
    aliases.push(`export type ${name} = ${ns}.${name};`);
  }

  const header = [
    "// AUTO-GENERATED by `npm run gen:types` from ../fixtures/schema/*.json.",
    "// Do not edit by hand. Regenerate instead; the output is deterministic.",
    "/* eslint-disable */",
    "",
  ].join("\n");

  const body = blocks.join("\n\n") + "\n\n" + aliases.join("\n");
  await writeFile(outFile, header + body + "\n", "utf8");
  // eslint-disable-next-line no-console
  console.log(`wrote ${outFile} from ${files.length} schema(s)`);
}

main().catch((err) => {
  // eslint-disable-next-line no-console
  console.error(err);
  process.exit(1);
});
